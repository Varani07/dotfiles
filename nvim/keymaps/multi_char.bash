normal-mode

c : change
d : delete
y : yank
v : visual

i : inside
a : around

w : word
W : todos caracteres fora espaços
s : sentence
p : paragraph
t : dentro de tag

sem (i|a)
w : até o início da próxima palavra
e : até o fim da palavra atual
$ : até o fim da linha
0 : até o início da linha
G : até o fim do arquivo
gg: até o início do arquivo
k : linha atual mais linha de cima
j : linha atual mais linha abaixo
} : até próximo parágrafo
t : até antes do caracter
f : até o caracter

podem ser combinadas com números, ex.: 2ci(
